#!/usr/bin/python3 -I
"""Small, fixed-purpose Polkit adapter for an external Linux block source.

This executable is installed root-owned by the Debian package; never execute
it from a writable project directory. It launches the system PhotoRec for ONE
validated non-system, unmounted block source and listens for STOP on stdin.
No arbitrary command, options, or executable path is accepted.
"""
import os
import re
import signal
import subprocess
import sys
from pathlib import Path

if __package__ in (None, ''):
    sys.path.insert(0, '/usr/share/sectorrec')
from src.helpers.bundled_tools import binary, isolated_tool_env


def stop(child):
    if child.poll() is not None:return
    for sig, timeout in ((signal.SIGINT, 3), (signal.SIGTERM, 3), (signal.SIGKILL, 2)):
        try:
            os.killpg(child.pid, sig)
            child.wait(timeout=timeout)
            return
        except ProcessLookupError:
            return
        except subprocess.TimeoutExpired:
            continue



def restore_ownership(parent, prefix, uid, gid):
    """Return PhotoRec-created output to the authorizing user, no symlinks.

    Traversal is relative to opened directory descriptors. Malicious symlink
    names are never opened or followed, even during races with other users.
    """
    directory_flags = os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW
    file_flags = os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK
    seen = [0]
    def visit(fd, depth=0):
        if depth > 32 or seen[0] >= 300_000:return
        with os.scandir(fd) as iterator:
            for entry in iterator:
                if seen[0] >= 300_000:break
                seen[0] += 1
                try:
                    if entry.is_symlink():continue
                    if entry.is_dir(follow_symlinks=False):
                        child=os.open(entry.name, directory_flags, dir_fd=fd)
                        try:
                            visit(child, depth+1)
                            os.fchown(child,uid,gid)
                        finally:os.close(child)
                    elif entry.is_file(follow_symlinks=False):
                        child=os.open(entry.name,file_flags,dir_fd=fd)
                        try:os.fchown(child,uid,gid)
                        finally:os.close(child)
                except (OSError,PermissionError):continue
    root=os.open(str(parent),directory_flags)
    try:
        with os.scandir(root) as iterator:
            for entry in iterator:
                is_output=(entry.name.startswith(prefix+'.') and entry.name[len(prefix)+1:].isdigit())
                is_session=(entry.name=='.sectorrec_'+prefix[len('SectorRec_'):])
                if not (is_output or is_session) or entry.is_symlink() or not entry.is_dir(follow_symlinks=False):
                    continue
                try:
                    sub=os.open(entry.name,directory_flags,dir_fd=root)
                    try:
                        visit(sub)
                        os.fchown(sub,uid,gid)
                    finally:os.close(sub)
                except OSError:continue
    finally:os.close(root)


def validate_output_prefix(name):
    """Accept only a SectorRec session prefix generated by PhotoRecWorker.

    The launcher must track the same naming convention as the unprivileged
    worker. Strict characters and suffix validation keep privileged output
    within the user-selected destination folder.
    """
    return bool(re.fullmatch(r'SectorRec_(?:\d{6}|\d{8})(?:_[1-9]\d{0,2})?', name))


def session_name(prefix):
    if not validate_output_prefix(prefix):
        raise ValueError('Invalid output directory prefix')
    return '.sectorrec_' + prefix[len('SectorRec_'):]


def run(argv):
    if os.geteuid()!=0 or len(argv)!=4:
        raise RuntimeError('This guarded PhotoRec launcher needs Polkit authorization')
    original_uid=os.environ.get('PKEXEC_UID') or os.environ.get('SUDO_UID')
    if not original_uid or not original_uid.isdecimal():
        raise RuntimeError('Cannot identify requesting user')
    from src.helpers.reader import verify_device
    from src.services.signature import ensure_different_disk, photorec_command, FORMAT_PRESETS
    preset = argv[3]
    if preset not in FORMAT_PRESETS:
        raise RuntimeError('Unknown signature selection')
    # OS volumes are permitted for read-only carving only. Writing is guarded
    # independently against the source physical disk below.
    source=verify_device(argv[1], allow_unknown=True, allow_system_read=True)
    prefix=Path(argv[2]);parent=prefix.parent
    if not validate_output_prefix(prefix.name):
        raise RuntimeError('Invalid output directory prefix')
    if not parent.is_dir() or parent.is_symlink() or parent.resolve()!=parent:
        raise RuntimeError('Destination must be a real, canonical directory')
    ensure_different_disk(source, parent)
    # Check destination permission as the original (non-root) user.
    uid=int(original_uid)
    try:
        os.seteuid(uid)
        writable=os.access(parent,os.W_OK|os.X_OK,effective_ids=True)
    finally:
        os.seteuid(0)
    if not writable:
        raise RuntimeError('Destination must be writable by requesting user')
    photo_binary=binary('photorec')
    if not Path(photo_binary).is_file():
        raise RuntimeError('PhotoRec not installed at /usr/bin/photorec')
    import pwd
    gid=pwd.getpwuid(uid).pw_gid
    session=parent/session_name(prefix.name)
    if not session.is_dir() or session.is_symlink():
        raise RuntimeError('Session directory missing or invalid')
    env=isolated_tool_env({'HOME': str(parent)})
    child=subprocess.Popen(photorec_command(photo_binary,source,prefix,preset),cwd=session,
                           env=env,stdin=subprocess.DEVNULL,start_new_session=True)
    try:
        import select
        while child.poll() is None:
            if select.select([sys.stdin],[],[],.25)[0]:
                line=sys.stdin.readline()
                if line.strip()=='STOP' or not line:
                    stop(child)
                    return 130
        return child.wait()
    finally:
        if child.poll() is None:stop(child)
        restore_ownership(parent,prefix.name,uid,gid)


if __name__=='__main__':
    try:
        sys.exit(run(sys.argv))
    except (ValueError,OSError,RuntimeError) as exc:
        print('SectorRec PhotoRec: '+str(exc),file=sys.stderr)
        sys.exit(2)
